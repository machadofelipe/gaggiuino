SIDES = [("orig", "O", "Original HMI", "#f59e0b"), ("gemini", "G", "Gemini redesign (75b78f4)", "#a78bfa"),
         ("opus", "C", "This branch (Opus review)", "#38bdf8")]


def resolve_refs(finding, data):
    out = []
    for side_key, tag, _, _ in SIDES:
        for ref in finding.get("refs", {}).get(tag, []):
            page, name = ref.split(".", 1)
            hit = None
            for key in finding["screens"] or [k for k, p, _ in SCREENS if p == page]:
                scr = data[side_key].get(key)
                if scr and scr["page"] == page:
                    hit = next((c["easyId"] for c in scr["components"] if c["name"] == name), None)
                    if hit:
                        break
            out.append(dict(side=tag, ref=ref, easyId=hit))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--orig", type=Path, required=True)
    ap.add_argument("--gemini", type=Path, required=True)
    ap.add_argument("--opus", type=Path, required=True)
    ap.add_argument("--probe", type=Path, help="optional JSON of simulator bug probes")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--md", type=Path, help="also write the findings as Markdown")
    a = ap.parse_args()
    data = {k: json.loads(getattr(a, k).read_text()) for k in ("orig", "gemini", "opus")}
    screens = [dict(key=k, page=p, title=t, sides={s: data[s][k] for s, *_ in SIDES}) for k, p, t in SCREENS]
    findings = [dict(f, resolved=resolve_refs(f, data)) for f in FINDINGS]
    probe = json.loads(a.probe.read_text()) if a.probe else None
    page = TEMPLATE.replace("__SCREENS__", json.dumps(screens)) \
                   .replace("__FINDINGS__", json.dumps(findings)) \
                   .replace("__SIDES__", json.dumps([dict(key=s, tag=t, label=l, color=c) for s, t, l, c in SIDES])) \
                   .replace("__PROBE__", json.dumps(probe))
    a.out.write_text(page, encoding="utf-8")
    print(f"wrote {a.out} ({a.out.stat().st_size // 1024} KB)")
    if a.md:
        a.md.write_text(markdown(findings, probe), encoding="utf-8")
        print(f"wrote {a.md}")


def markdown(findings, probe):
    titles = {k: t for k, _, t in SCREENS}
    out = ["# DeLonghi HMI review (Gemini redesign 75b78f4 -> mac_delongui_opus)", "",
           "Generated by `tools/hmi/build_review_page.py` from `tools/hmi/review_findings.py`. "
           "Interactive version with Original / Gemini / this-branch screenshots and hover IDs: "
           "`docs/delongui-hmi-review.html` (rebuild with `tools/hmi/compare.sh`).", "",
           "IDs: `G..` = Gemini build (same numbering as the earlier `N..` IDs), `C..` = this branch.", ""]
    if probe:
        out += ["## Simulator bug probes", "", "| Probe | Gemini | This branch | Expected |", "|---|---|---|---|"]
        out += [f"| {p['name']} | `{p['gemini']}` | `{p['opus']}` | `{p['expect']}` |" for p in probe]
        out.append("")
    for status, head in (("fixed", "Fixed in this branch"), ("next", "Next steps (explicit instructions)")):
        out += [f"## {head}", ""]
        for f in (f for f in findings if f["status"] == status):
            ids = ", ".join(f"`{r['easyId']}`" for r in f["resolved"] if r["easyId"])
            scr = ", ".join(f"{k} {titles.get(k, '')}" for k in f["screens"]) or "all"
            out += [f"### {f['id']} ({f['sev']}): {f['title']}", "",
                    f"- **Screens:** {scr}" + (f"; widgets {ids}" if ids else ""),
                    f"- **Problem:** {f['problem']}",
                    f"- **{'Change' if status == 'fixed' else 'Instruction'}:** {f['instruction']}"]
            if f.get("evidence"):
                out.append(f"- **Evidence:** {f['evidence']}")
            out.append("")
    return "\n".join(out)


