#!/usr/bin/env python3
"""Build a self-contained 3-way review page: Original vs Gemini redesign vs this branch.

Inputs are capture_screens.py JSON files. Hover a widget for its ID (O/G/C + screen
key + reading-order number), click it to copy and add a note; notes persist in
localStorage and export as Markdown. Each screen shows the review findings attached
to it, with the referenced widgets resolved to IDs.

  build_review_page.py --orig o.json --gemini g.json --opus c.json --out page.html
"""
import argparse
